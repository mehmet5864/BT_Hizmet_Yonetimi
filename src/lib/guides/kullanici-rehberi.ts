const CAPTION =
  "Şema: ekran düzenini ve numaralı alanları gösterir; gerçek ekran görüntüsü değildir. Düğme adları ve renkler sürüme ve temaya göre farklı olabilir.";

function menu(e: Entry): GuideBlock[] {
  return [
    { t: "h1", text: e.title },
    { t: "p", text: `Menü yolu: ${e.path}. Kimler kullanır: ${e.who}.` },
    { t: "img", src: `/guides/${e.img}.svg`, alt: `${e.title} ekran şeması`, caption: CAPTION },
    { t: "h2", text: "Ne işe yarar" },
    { t: "p", text: e.what },
    { t: "h2", text: "Ekranda neler var (resimdeki numaralar)" },
    { t: "ol", items: e.marks },
    { t: "h2", text: "Nasıl çalışılır" },
    { t: "ol", items: e.how },
    { t: "h2", text: "Nasıl olmalı: ITIL, Agile ve DevSecOps gözüyle" },
    {
      t: "table",
      headers: ["Çerçeve", "Bu menüde beklenen uygulama"],
      rows: [
        ["ITIL", e.itil],
        ["Agile", e.agile],
        ["DevSecOps", e.devsecops],
      ],
    },
    ...(e.tip ? ([{ t: "note", title: "İpucu", text: e.tip }] as GuideBlock[]) : []),
  ];
}

