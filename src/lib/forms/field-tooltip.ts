export function fieldTooltip(field: {
  id?: string;
  key?: string;
  label: string;
  hint?: string;
  kind?: FieldKind | string;
  required?: boolean;
  placeholder?: string;
}) {
  if (field.hint?.trim()) return field.hint.trim();
  const byId = (field.id && FIELD_ID_HELP[field.id]) || (field.key && FILTER_KEY_HELP[field.key]);
  if (byId) return byId;
  const extra = field.required ? " Zorunlu alandır." : "";
  switch (field.kind) {
    case "person":
      return `${field.label} personel listesinden seçilir.${extra}`;
    case "department":
      return `${field.label} birim listesinden seçilir.${extra}`;
    case "vendor":
      return `${field.label} kayıtlı firma listesinden seçilir.${extra}`;
    case "catalog":
      return `${field.label} hizmet kataloğundan seçilir.${extra}`;
    case "date":
      return `${field.label} için tarihi seçin.${extra}`;
    case "select":
      return `${field.label} için listeden uygun değeri seçin.${extra}`;
    case "textarea":
      return `${field.label} alanına ayrıntıyı yazın.${extra}`;
    case "password":
      return `${field.label}: boş bırakılırsa mevcut değer korunur.`;
    case "image":
      return `${field.label} için görsel yükleyebilirsiniz.`;
    case "location":
      return `${field.label}: oda, koridor, kabin ve raf bilgisi.`;
    case "assetRefs":
    case "serviceRefs":
      return `${field.label} için ilgili envanter kayıtlarını seçin.`;
    default:
      if (field.placeholder) return `${field.label}: ${field.placeholder}.${extra}`.replace("..", ".");
      return `${field.label} alanını doldurun.${extra}`;
  }
}
