def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def ts_key(k: str) -> str:
    if str(k).isidentifier():
        return k
    return json.dumps(k, ensure_ascii=False)


def obj_str(d: dict[str, str], indent=4) -> str:
    lines = ["{"]
    for k, v in d.items():
        lines.append(f'{" " * indent}{ts_key(k)}: "{esc(v)}",')
    lines.append(f'{" " * (indent - 2)}}}')
    return "\n".join(lines)


