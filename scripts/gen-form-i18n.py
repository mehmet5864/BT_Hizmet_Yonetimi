def fields_block(locale: str) -> str:
    if locale == "tr":
        return "{}"
    lines = ["{"]
    ids = list(EXTRACT["fields"].keys()) + [k for k in FIELD_L if k not in EXTRACT["fields"]]
    for fid in ids:
        trans = FIELD_L.get(fid)
        if not trans:
            continue
        i = IDX[locale]
        entry = {"label": trans[i]}
        ph = PLACEHOLDER_L.get(fid)
        if ph:
            entry["placeholder"] = ph[i]
        inner = ", ".join(f'{k}: "{esc(v)}"' for k, v in entry.items())
        lines.append(f'      {fid}: {{ {inner} }},')
    lines.append("    }")
    return "\n".join(lines)


def options_block(locale: str) -> str:
    if locale == "tr":
        return "{}"
    lines = ["{"]
    for val, label in EXTRACT["options"].items():
        trans = OPTION_L.get(val)
        text = trans[IDX[locale]] if trans else label
        if not val.isidentifier():
            lines.append(f'      {json.dumps(val)}: "{esc(text)}",')
        else:
            lines.append(f'      {val}: "{esc(text)}",')
    lines.append("    }")
    return "\n".join(lines)


def map_block(src_tr: dict, src_x: dict, locale: str) -> str:
    lines = ["{"]
    if locale == "tr":
        for k, v in src_tr.items():
            key = json.dumps(k) if not k.isidentifier() else k
            lines.append(f'      {key}: "{esc(v)}",')
    else:
        for k, tup in src_x.items():
            key = json.dumps(k) if not str(k).isidentifier() else k
            lines.append(f'      {key}: "{esc(tup[IDX[locale]])}",')
    lines.append("    }")
    return "\n".join(lines)


